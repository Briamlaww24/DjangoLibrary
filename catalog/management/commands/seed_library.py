from datetime import timedelta

from django.conf import settings
from django.contrib.auth import get_user_model
from django.core.management.base import BaseCommand, CommandError
from django.db import transaction
from django.db.models import Q
from django.utils import timezone

from catalog.classics import CLASSICS
from catalog.models import Author, Book, Category, Loan
from catalog.roles import configureRoles


LEGACY_BOOKS = (
    ("el-bosque-de-la-niebla", "El bosque de la niebla"),
    ("la-ultima-marea", "La última marea"),
    ("mapa-de-estrellas", "Mapa de estrellas"),
    ("el-bosque-edicion-de-lectura", "El bosque de la niebla · edición de lectura"),
    ("marea-edicion-comentada", "La última marea · edición comentada"),
)

DEMO_ACCOUNTS = [
    ("demo_super", "DemoSuper-Libros268!"),
    ("demo_admin", "DemoAdmin-Libros268!"),
    ("demo_lector", "DemoLector-Libros268!"),
]


class Command(BaseCommand):
    help = "Carga cinco registros por entidad y tres cuentas de demostración en desarrollo."

    def add_arguments(self, parser):
        parser.add_argument(
            "--replace-existing", action="store_true",
            help="Sustituye solo los libros ficticios identificados como datos de ejemplo.",
        )

    @transaction.atomic
    def handle(self, *args, **options):
        if not settings.DEBUG:
            raise CommandError("Los datos de demostración solo se pueden cargar en desarrollo.")

        replaced = self.replaceLegacyBooks()
        if options["replace_existing"]:
            self.stdout.write(self.style.SUCCESS(f"Libros de ejemplo sustituidos: {replaced}."))
            return

        administrators, consultants = configureRoles()
        users = get_user_model().objects
        accounts = {}
        for username, password in DEMO_ACCOUNTS:
            user, created = users.get_or_create(username=username, defaults={
                "email": f"{username}@example.test",
                "is_superuser": username == "demo_super",
                "is_staff": username != "demo_lector",
            })
            if created:
                user.set_password(password)
                user.save(update_fields=["password"])
                if username == "demo_admin":
                    user.groups.add(administrators)
                if username == "demo_lector":
                    user.groups.add(consultants)
            accounts[username] = user

        borrower = accounts["demo_lector"]
        borrowedOn = timezone.localdate()
        for position, classic in enumerate(CLASSICS):
            category, _ = Category.objects.get_or_create(name=classic.genre)
            book, created = Book.objects.get_or_create(slug=classic.slug, defaults={
                **self.bookFields(classic, category),
                "owner": accounts["demo_admin"],
            })
            if created:
                author, _ = Author.objects.get_or_create(name=classic.author)
                book.authors.add(author)
            Loan.objects.get_or_create(book=book, borrower=borrower, defaults={
                "borrowed_on": borrowedOn,
                "due_on": borrowedOn + timedelta(days=14),
                "status": Loan.Status.RETURNED if position % 2 else Loan.Status.ACTIVE,
            })

        self.stdout.write(self.style.SUCCESS("Datos de biblioteca cargados."))

    @staticmethod
    def bookFields(classic, category):
        return {
            "title": classic.title,
            "genre": classic.genre,
            "description": f"{classic.description} Texto en {classic.language.lower()}.",
            "extract": classic.extract,
            "category": category,
        }

    def replaceLegacyBooks(self):
        replaced = 0
        for (slug, title), classic in zip(LEGACY_BOOKS, CLASSICS, strict=True):
            book = (
                Book.objects.select_for_update()
                .filter(Q(owner__isnull=True) | Q(owner__username="demo_admin"), slug=slug, title__in=[slug, title])
                .first()
            )
            if book is None or Book.objects.filter(slug=classic.slug).exists():
                continue
            # Original sample files are bundled or use the autogenerated demo filename.
            files = [(book.pdf, f"catalog/pdf/{slug}.pdf"), (book.cover, f"catalog/covers/{slug}.jpg")]
            if any(file and file.name != sample for file, sample in files):
                continue
            author, _ = Author.objects.get_or_create(name=classic.author)
            category, _ = Category.objects.get_or_create(name=classic.genre)
            fields = self.bookFields(classic, category)
            updatedFields = {**fields, "slug": classic.slug, "rating": None, "pdf": None, "cover": None}
            for field, value in updatedFields.items():
                setattr(book, field, value)
            book.save(update_fields=list(updatedFields))
            book.authors.set([author])
            replaced += 1
        return replaced
